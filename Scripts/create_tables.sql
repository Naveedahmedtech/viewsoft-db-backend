-- ==========================================================
-- 13. Legacy View: public.project_annotation
-- ==========================================================
DROP VIEW IF EXISTS public.project_annotation CASCADE;

CREATE VIEW public.project_annotation AS
SELECT
    a.id         AS anno_id,
    a.created_by,
    a.updated_by,
    a.created_at,
    a.updated_at,
    p.id         AS proj_id,
    p.name       AS proj_name,
    p."desc"     AS proj_desc
FROM public.annotation a
JOIN public.project   p ON a.proj_id = p.id;

COMMIT;
