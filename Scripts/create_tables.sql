-- ==========================================================
--  CREATE TABLES SCRIPT (Full Variant with Legacy Tables)
--  Project: rx-back-end
--  Notes:
--    * Uses IDENTITY (no external sequences required)
--    * Creates annotation_event_log BEFORE trigger function
--    * Schema-qualified references inside the trigger
--    * Adds poller-friendly index
